"""Ограничитель скорости backfill: не более `rate` отправок в секунду, РАВНОМЕРНО (шаг 6).

Первая версия была «скользящим окном» (не более N отправок за любую секунду). Формально она соблюдает лимит,
но выдаёт все N отправок подряд в начале секунды и затем молчит: на стороне брокера это пачки по 50-200
сообщений, и из-за дрожания задержек окно 1 с на приёмной стороне видело до 1.4 x лимита (см. отчёт).
Теперь между двумя отправками выдерживается пауза не короче 1/rate секунд, отсчитанная от ФАКТИЧЕСКОГО
момента предыдущей отправки, поэтому в любом окне 1 с отправок не больше rate, а нагрузка на брокер ровная.
Цена - скорость чуть ниже лимита на величину перерасхода таймера (около 0.1 мс на отправку).
"""
import asyncio
import time


class RateLimiter:
    def __init__(self):
        self._next = 0.0           # не раньше этого момента (time.monotonic) можно отправлять

    async def acquire(self, rate: float) -> None:
        """rate <= 0 - без ограничения. После простоя «кредит» не копится: первая отправка идёт сразу."""
        if rate <= 0:
            return
        now = time.monotonic()
        if self._next > now:
            await asyncio.sleep(self._next - now)
            now = time.monotonic()
        self._next = now + 1.0 / rate
